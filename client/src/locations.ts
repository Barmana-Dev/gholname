export const provinces = IRAN_LOCATIONS;

export function citiesForProvince(province: string): LocalCity[] {
  return provinces.find((item) => item.value === province)?.cities ?? [];
}

export function sectionsForCity(province: string, cityName: string): string[] {
  return (
    citiesForProvince(province).find((item) => item.value === cityName)
      ?.sections ?? []
  );
}
